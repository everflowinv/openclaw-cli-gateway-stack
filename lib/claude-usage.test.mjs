import test from 'node:test';
import assert from 'node:assert/strict';
import { ClaudeUsageTracker } from './claude-usage.mjs';
import { priceUsage } from './usage-cost.mjs';
test('final stream usage replaces initial counts and stale replay cannot lower them', () => {
  const events = [], t = new ClaudeUsageTracker(call => events.push(call));
  const first = { id: 'one', model: 'm', usage: { input_tokens: 10, cache_creation_input_tokens: 20, cache_read_input_tokens: 30, output_tokens: 1 } };
  t.accept({type:'stream_event',event:{type:'message_start',message:first}});
  t.accept({type:'stream_event',event:{type:'message_delta',delta:{stop_reason:'tool_use'},usage:{output_tokens:150}}});
  t.accept({type:'assistant',message:first});
  assert.equal(events.length,2);
  assert.deepEqual(t.foreground[0].usage,{...first.usage,output_tokens:150});
  assert.equal(t.foreground[0].complete,true);
  t.accept({type:'stream_event',parent_tool_use_id:'child',event:{type:'message_start',message:{id:'child',usage:{output_tokens:2}}}});
  t.accept({type:'stream_event',parent_tool_use_id:'child',event:{type:'message_delta',delta:{stop_reason:'end_turn'},usage:{output_tokens:90}}});
  assert.equal(t.foreground.length,1);
  assert.equal(t.calls.get('child').usage.output_tokens,90);
});
test('pricing counts each token once and leaves unpriced/context-tier aggregates unknown', () => {
  const rates={input:2,cacheWrite:4,cacheRead:.2,output:10};
  const legacy={prompt_tokens:110,cache_creation_input_tokens:20,prompt_tokens_details:{cached_tokens:100},completion_tokens:5};
  const canonical={...legacy,prompt_tokens:130,prompt_tokens_details:{cached_tokens:100,cache_write_tokens:20}};
  assert.equal(priceUsage(rates,legacy),.00017);
  assert.equal(priceUsage(rates,canonical),.00017);
  assert.equal(priceUsage(null,legacy),null);
  assert.equal(priceUsage({input:2},legacy),null);
  const tiered={...rates,tieredPricing:[{range:[100,null],input:4}]};
  assert.equal(priceUsage(tiered,legacy),null);
  assert.equal(priceUsage(tiered,legacy,{perCall:true}),.00019);
});
